"""Bundle each Open WebUI function into one installable file under bundled/.

Open WebUI stores a function as a single Python source, so it cannot import config.py or
api_endpoint.py. Every `from frontend.openwebui.<module> import …  # inline` line is replaced by
that module's code (once per bundle, recursively). Run from the repository root:

    uv run python frontend/openwebui/build_functions.py          # write bundled/
    uv run python frontend/openwebui/build_functions.py --check  # fail if bundled/ is stale
"""

import ast
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DIST = HERE / "bundled"
# installed function id (file name in bundled/) → source module
FUNCTIONS = {"manastu_engine.py": "pipe_manastu_engine.py", "manastu_actions.py": "actions_manastu.py"}
INLINE = re.compile(r"^from frontend\.openwebui\.(\w+) import .+  # inline$")


def _body_without_docstring(source: str) -> list[str]:
    tree = ast.parse(source)
    lines = source.splitlines()
    first = tree.body[0] if tree.body else None
    is_docstring = isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant)
    if is_docstring and isinstance(first.value.value, str):
        return lines[first.end_lineno :]
    return lines


def _expand(lines: list[str], seen: set[str]) -> list[str]:
    out: list[str] = []
    skipping_names = False  # inside a parenthesized `from … import (  # inline` block
    for line in lines:
        if skipping_names:
            skipping_names = line.strip() != ")"
            continue
        match = INLINE.match(line)
        if not match:
            out.append(line)
            continue
        skipping_names = line.rstrip().endswith("(  # inline")
        module = match.group(1)
        if module in seen:
            continue
        seen.add(module)
        source = (HERE / f"{module}.py").read_text()
        out.append(f"# ---- inlined from frontend/openwebui/{module}.py")
        body = _expand(_body_without_docstring(source), seen)
        while body and not body[-1].strip():
            body.pop()
        out += [*body, "", "", f"# ---- end of {module}.py"]  # PEP 8 spacing keeps ruff format stable
    return out


def bundle(source_name: str) -> str:
    source = (HERE / source_name).read_text()
    tree = ast.parse(source)
    docstring_end = tree.body[0].end_lineno  # the frontmatter docstring Open WebUI reads must stay first
    lines = source.splitlines()
    header = [
        *lines[:docstring_end],
        "",
        f"# GENERATED by frontend/openwebui/build_functions.py from {source_name}; edit the sources.",
        "# ruff: noqa",
    ]
    text = "\n".join(header + _expand(lines[docstring_end:], set())) + "\n"
    if "frontend.openwebui" in text.replace("frontend/openwebui", ""):
        raise SystemExit(f"{source_name}: a frontend.openwebui import was not inlined")
    ast.parse(text)
    return text


def main(check: bool) -> int:
    DIST.mkdir(exist_ok=True)
    stale = []
    for target, source_name in FUNCTIONS.items():
        text = bundle(source_name)
        path = DIST / target
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(target)
        else:
            path.write_text(text)
    if stale:
        print(f"stale bundles in {DIST}: {', '.join(stale)}; run build_functions.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main("--check" in sys.argv[1:]))
